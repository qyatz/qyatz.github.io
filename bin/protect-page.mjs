#!/usr/bin/env node
// Encrypt / decrypt password-protected pages (e.g. _hobbies/*.md).
//
// The repository is public, so only the encrypted body is committed. The page
// is decrypted in the browser by assets/js/protected-page.js.
//
// Usage:
//   PAGE_PASSWORD=0000 node bin/protect-page.mjs encrypt <plain.md> <out.md>
//   PAGE_PASSWORD=0000 node bin/protect-page.mjs decrypt <out.md> > <plain.md>
//
// <plain.md> is a normal Jekyll page: YAML front matter + Markdown body.
// Keep plaintext files out of git (e.g. under the ignored _private/ folder).

import crypto from "node:crypto";
import fs from "node:fs";

const ITERATIONS = 600000;
const FRONT_MATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;
const PAYLOAD = /data-payload="([A-Za-z0-9+/=]+)"/;

function fail(message) {
  console.error(message);
  process.exit(1);
}

function split(text, file) {
  const match = text.match(FRONT_MATTER);
  if (!match) fail(`${file}: missing YAML front matter`);
  return { frontMatter: match[1], body: text.slice(match[0].length) };
}

function deriveKey(password, salt, iterations) {
  return crypto.pbkdf2Sync(password, salt, iterations, 32, "sha256");
}

function encrypt(plaintext, password) {
  const salt = crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv("aes-256-gcm", deriveKey(password, salt, ITERATIONS), iv);
  const ciphertext = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final(), cipher.getAuthTag()]);
  const payload = { v: 1, iter: ITERATIONS, salt: salt.toString("base64"), iv: iv.toString("base64"), ct: ciphertext.toString("base64") };
  return Buffer.from(JSON.stringify(payload)).toString("base64");
}

function decrypt(encoded, password) {
  const payload = JSON.parse(Buffer.from(encoded, "base64").toString("utf8"));
  const data = Buffer.from(payload.ct, "base64");
  const decipher = crypto.createDecipheriv(
    "aes-256-gcm",
    deriveKey(password, Buffer.from(payload.salt, "base64"), payload.iter),
    Buffer.from(payload.iv, "base64")
  );
  decipher.setAuthTag(data.subarray(data.length - 16));
  try {
    return Buffer.concat([decipher.update(data.subarray(0, data.length - 16)), decipher.final()]).toString("utf8");
  } catch {
    fail("Wrong password.");
  }
}

const [command, input, output] = process.argv.slice(2);
const password = process.env.PAGE_PASSWORD;
if (!password) fail("Set the password in the PAGE_PASSWORD environment variable.");

if (command === "encrypt" && input && output) {
  const { frontMatter, body } = split(fs.readFileSync(input, "utf8"), input);
  const cleanFrontMatter = frontMatter.replace(/^(protected|sitemap):.*\r?\n?/gm, "").trimEnd();
  const page = [
    "---",
    cleanFrontMatter,
    "protected: true",
    "sitemap: false",
    "---",
    "",
    "<!-- Generated by bin/protect-page.mjs. Do not edit by hand; decrypt, edit, and re-encrypt. -->",
    "",
    `<div class="protected-page" data-payload="${encrypt(body, password)}">`,
    "  <noscript>This page requires JavaScript.</noscript>",
    "</div>",
    "<script src=\"{{ '/assets/js/protected-page.js' | relative_url }}\" defer></script>",
    "",
  ].join("\n");
  fs.writeFileSync(output, page);
  console.error(`Encrypted ${input} -> ${output}`);
} else if (command === "decrypt" && input) {
  const text = fs.readFileSync(input, "utf8");
  const { frontMatter, body } = split(text, input);
  const match = body.match(PAYLOAD);
  if (!match) fail(`${input}: no encrypted payload found`);
  const cleanFrontMatter = frontMatter.replace(/^(protected|sitemap):.*\r?\n?/gm, "").trimEnd();
  process.stdout.write(`---\n${cleanFrontMatter}\n---\n${decrypt(match[1], password)}`);
} else {
  fail("Usage:\n  node bin/protect-page.mjs encrypt <plain.md> <out.md>\n  node bin/protect-page.mjs decrypt <out.md> > <plain.md>");
}
